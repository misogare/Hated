/** The production `ApiServices`: each one a call into `@hated/db`. */

import {
  addPhoto,
  announceTyping,
  createSession,
  deleteAccount,
  deletePhoto,
  exportAccount,
  getAccount,
  getActiveQuestionnaire,
  getAnswers,
  getDesires,
  getLatestResult,
  getMatch,
  listMatches,
  listPhotos,
  listMessages,
  passMatch,
  PROMPTS,
  readPhoto,
  registerPushToken,
  reorderPhotos,
  reportMatch,
  resolveSession,
  revokeAllSessions,
  revokeSession,
  unregisterAllPushTokens,
  unregisterPushToken,
  saveAnswers,
  saveDesires,
  saveProfile,
  saveWords,
  sayHello,
  sendMessage,
  setNotificationPrefs,
  setProfileActive,
  startSignIn,
  verifyCode,
  type Mailer,
  type PhotoStore,
  type PrismaClient,
} from '@hated/db';

import type { ApiServices } from './app.js';

export function createDbServices(
  prisma: PrismaClient,
  mailer: Mailer,
  photos: PhotoStore,
  /** How long people have to say hello after a round. Default 24 hours. */
  window: { helloWindowMs?: number } = {},
): ApiServices {
  return {
    startSignIn: (email) => startSignIn(prisma, { email }, { mailer }),
    verifyCode: (input) => verifyCode(prisma, input),
    createSession: (userId) => createSession(prisma, userId),
    resolveSession: (token) => resolveSession(prisma, token),
    revokeSession: (token) => revokeSession(prisma, token),
    revokeAllSessions: (userId) => revokeAllSessions(prisma, userId),
    getAccount: (userId) => getAccount(prisma, userId),
    saveProfile: (userId, input) => saveProfile(prisma, userId, input),
    setProfileActive: (userId, active) => setProfileActive(prisma, userId, active),
    getQuestionnaire: () => getActiveQuestionnaire(prisma),
    getAnswers: (userId) => getAnswers(prisma, userId),
    saveAnswers: (userId, answers) => saveAnswers(prisma, userId, answers),
    getDesires: (userId) => getDesires(prisma, userId),
    saveDesires: (userId, desires) => saveDesires(prisma, userId, desires),
    getLatestResult: (userId) => getLatestResult(prisma, userId, window),
    sayHello: (userId, matchId) => sayHello(prisma, userId, matchId, window),
    passMatch: (userId, matchId) => passMatch(prisma, userId, matchId),
    listMessages: (userId, matchId, after) => listMessages(prisma, userId, matchId, { after }),
    sendMessage: (userId, matchId, body) => sendMessage(prisma, userId, matchId, body),
    announceTyping: (userId, matchId) => announceTyping(prisma, userId, matchId),
    listMatches: (userId) => listMatches(prisma, userId, window),
    reportMatch: (userId, matchId, input) => reportMatch(prisma, userId, matchId, input),
    registerPushToken: (userId, token, platform) => registerPushToken(prisma, userId, token, platform),
    unregisterPushToken: (userId, token) => unregisterPushToken(prisma, userId, token),
    unregisterAllPushTokens: (userId) => unregisterAllPushTokens(prisma, userId),
    setNotificationPrefs: (userId, changes) => setNotificationPrefs(prisma, userId, changes),
    deleteAccount: (userId) => deleteAccount(prisma, photos, userId),
    exportAccount: (userId) => exportAccount(prisma, photos, userId),
    listPhotos: (userId) => listPhotos(prisma, userId),
    addPhoto: (userId, upload) => addPhoto(prisma, photos, userId, upload),
    deletePhoto: (userId, photoId) => deletePhoto(prisma, photos, userId, photoId),
    reorderPhotos: (userId, ids) => reorderPhotos(prisma, userId, ids),
    readPhoto: (userId, photoId, variant) => readPhoto(prisma, photos, userId, photoId, variant),
    saveWords: (userId, input) => saveWords(prisma, userId, input),
    promptChoices: () => PROMPTS.map((prompt) => ({ key: prompt.key, label: prompt.label })),
    getMatch: (userId, matchId) => getMatch(prisma, userId, matchId, window),
  };
}
